using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Rocket.Surgery.ModularPipelines.Extensions.Analyzers;

/// <summary>
///     Writes <c>TestShard1</c> to <c>TestShardN</c>, one test module per shard, into a build host whose <c>RocketTestShards</c> MSBuild
///     property is more than one. ModularPipelines schedules modules by type, so only distinct module types run side by side.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TestShardGenerator : IIncrementalGenerator
{
    /// <summary>The namespace of the generated shards.</summary>
    public const string Namespace = "Rocket.Surgery.ModularPipelines.Extensions.Modules.Shards";

    /// <summary>More shards than this is a mistake, not a plan.</summary>
    public const int MaximumShards = 64;

    private const string ShardBaseMetadataName = "Rocket.Surgery.ModularPipelines.Extensions.Modules.TestShardModule";

    private static readonly DiagnosticDescriptor InvalidShardCount = new(
        "RSMP0001",
        "Invalid RocketTestShards",
        "RocketTestShards must be a whole number from 0 to {1}, but is '{0}'; no test shards were generated",
        "Usage",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true
    );

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var shardCount = context.AnalyzerConfigOptionsProvider.Select(
            static (options, _) => options.GlobalOptions.TryGetValue("build_property.RocketTestShards", out var value) ? value.Trim() : ""
        );
        // Without the library the generated code could not compile.
        var hasLibrary = context.CompilationProvider.Select(static (compilation, _) => compilation.GetTypeByMetadataName(ShardBaseMetadataName) is not null);

        context.RegisterSourceOutput(
            shardCount.Combine(hasLibrary),
            static (production, input) =>
            {
                var (value, library) = input;
                if (value.Length == 0 || !library) return;

                if (!int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var count) || count > MaximumShards)
                {
                    production.ReportDiagnostic(Diagnostic.Create(InvalidShardCount, Location.None, value, MaximumShards));
                    return;
                }

                if (count > 1) production.AddSource("RocketTestShards.g.cs", SourceText.From(Generate(count), Encoding.UTF8));
            }
        );
    }

    /// <summary>The source of <paramref name="count" /> shards and their registration.</summary>
    internal static string Generate(int count)
    {
        var builder = new StringBuilder()
                     .AppendLine("// <auto-generated/>")
                     .AppendLine("#nullable enable")
                     .AppendLine("#pragma warning disable CA2255 // The build host is an application, and its shards must exist before the pipeline is built.")
                     .AppendLine()
                     .Append("namespace ").Append(Namespace).AppendLine(";")
                     .AppendLine();

        for (var shard = 1; shard <= count; shard++)
        {
            var number = shard.ToString(CultureInfo.InvariantCulture);
            builder
               .Append("/// <summary>Test shard ").Append(number).Append(" of ").Append(count.ToString(CultureInfo.InvariantCulture)).AppendLine(".</summary>")
               .Append("internal sealed partial class TestShard").Append(number)
               .Append("(global::Rocket.Surgery.ModularPipelines.Extensions.Modules.TestShardServices services)")
               .Append(" : global::Rocket.Surgery.ModularPipelines.Extensions.Modules.TestShardModule(services, ").Append(number).AppendLine(");")
               .AppendLine();
        }

        builder
           .AppendLine("internal static class RocketTestShardRegistration")
           .AppendLine("{")
           .AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]")
           .AppendLine("    internal static void Register() =>")
           .AppendLine("        global::Rocket.Surgery.ModularPipelines.Extensions.Modules.TestShards.Register(")
           .AppendLine("            [");
        for (var shard = 1; shard <= count; shard++)
        {
            builder
               .Append("                global::Rocket.Surgery.ModularPipelines.Extensions.Modules.TestShards.Describe<TestShard")
               .Append(shard.ToString(CultureInfo.InvariantCulture))
               .AppendLine(">(),");
        }

        return builder
              .AppendLine("            ]")
              .AppendLine("        );")
              .AppendLine("}")
              .ToString();
    }
}
